function botaniaFix(e, id, lines) {
  let changed = false
  for (let i = 0; i < lines.length; i++) {
    let s = String(lines[i].getString())
    if (s.indexOf("translation{key='") < 0 && s.indexOf('literal{') < 0) continue
    s = s.replace(COMPONENT_DEBUG, (m, key, lit) => key ? String(Text.translate(key).getString()) : lit)
    // armor set piece lines: "§a - Name" (worn) / " - Name" (missing)
    if (s.indexOf('§a - ') == 0) s = '§a  • ' + s.substring(5)
    else if (s.indexOf(' - ') == 0) s = '§8  • ' + s.substring(3)
    lines[i] = Text.literal(s)
    changed = true
  }
  return changed
}

